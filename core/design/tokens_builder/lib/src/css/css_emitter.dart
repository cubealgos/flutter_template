import 'package:tokens_builder/src/css/css_token_model.dart';

/// The theme [CssBuildResult.colorsByTheme] emits unconditionally under
/// `:root`, with every other theme layered on top inside its own
/// `@media (prefers-color-scheme: ...)` block. Matches this workspace's
/// `color.light.json`/`color.dark.json` convention (light is the
/// no-preference default).
const String _defaultTheme = 'light';

/// Renders a [CssBuildResult] to the full, deterministic CSS source of
/// `tokens.g.css`: one `:root { --token: value; }` block for every
/// theme-independent token plus the default theme's colours, and one
/// `@media (prefers-color-scheme: <theme>)` block per additional theme —
/// light/dark via the OS/browser preference, never a hand-toggled class or
/// `[data-theme]` attribute (this template has no theme switcher).
String emitCssSource(CssBuildResult result) {
  final buffer = StringBuffer()
    ..writeln('/*')
    ..writeln(' * GENERATED CODE - DO NOT MODIFY BY HAND')
    ..writeln(' *')
    ..writeln(
      ' * Generated by package:tokens_builder from core/design/ui/tokens/*.json.',
    )
    ..writeln(' * Run `melos run gen` to regenerate.')
    ..writeln(' */')
    ..writeln();

  final defaultColors = result.colorsByTheme[_defaultTheme] ?? const [];
  buffer
    ..writeln(':root {')
    ..write(_declarations(result.base, indent: '  '))
    ..write(_declarations(defaultColors, indent: '  '))
    ..writeln('}')
    ..writeln();

  final otherThemes = result.colorsByTheme.keys.toList()
    ..remove(_defaultTheme)
    ..sort();
  for (final theme in otherThemes) {
    final decls = result.colorsByTheme[theme] ?? const [];
    if (decls.isEmpty) continue;
    buffer
      ..writeln('@media (prefers-color-scheme: $theme) {')
      ..writeln('  :root {')
      ..write(_declarations(decls, indent: '    '))
      ..writeln('  }')
      ..writeln('}')
      ..writeln();
  }

  return buffer.toString();
}

String _declarations(List<CssTokenDecl> decls, {required String indent}) {
  final buffer = StringBuffer();
  for (final decl in decls) {
    if (decl.doc case final doc? when doc.isNotEmpty) {
      buffer.writeln('$indent/* ${doc.replaceAll('\n', ' ')} */');
    }
    buffer.writeln('$indent--${decl.name}: ${decl.value};');
  }

  return buffer.toString();
}
