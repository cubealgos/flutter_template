import 'package:dart_style/dart_style.dart';
import 'package:tokens_builder/src/model/resolved_token.dart';

/// The formatter every emitted `tokens.g.dart` is passed through before
/// it's returned — generating already-`dart format`-clean output is this
/// builder's own job, not a separate `dart format` step `melos run gen`
/// happens not to run (it's a bare `melos exec -- "dart run build_runner
/// build"`). Pinned to [DartFormatter.latestLanguageVersion]: the actual
/// generated syntax (const declarations, map literals) is fully
/// compatible with every recent language version, so there's no reason to
/// track the workspace's own `sdk:` constraint here.
final DartFormatter _formatter = DartFormatter(
  languageVersion: DartFormatter.latestLanguageVersion,
);

const Map<ScalarTokenKind, String> _mixClassName = {
  ScalarTokenKind.space: 'SpaceToken',
  ScalarTokenKind.radius: 'RadiusToken',
  ScalarTokenKind.double_: 'DoubleToken',
  ScalarTokenKind.textStyle: 'TextStyleToken',
  ScalarTokenKind.duration: 'DurationToken',
  ScalarTokenKind.fontWeight: 'FontWeightToken',
};

/// A 32-bit ARGB hex literal is always this many digits, zero-padded.
const int _argbHexDigits = 8;

/// ARGB hex literals are base 16.
const int _hexRadix = 16;

/// Renders a [BuildTokensResult] to the full, deterministic Dart source of
/// `tokens.g.dart`: one `const` `MixToken` (or plain constant) declaration
/// per resolved token, sorted by identifier, followed by an
/// `AppTokenValues` value collection per theme (`lightTokens`, `darkTokens`,
/// and any further discovered theme).
String emitTokensSource(BuildTokensResult result) {
  final buffer = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND')
    ..writeln('//')
    ..writeln(
      '// Generated by package:tokens_builder from core/design/ui/tokens/*.json.',
    )
    ..writeln('// Run `melos run gen` to regenerate.')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln("import 'package:mix/mix.dart';")
    ..writeln();

  _writeDeclarations(buffer, result);
  _writeSharedValueMaps(buffer, result);
  _writeThemedColorMaps(buffer, result);
  _writeAppTokenValuesClass(buffer);
  _writeThemeInstances(buffer, result);

  return _formatter.format(buffer.toString());
}

void _writeDeclarations(StringBuffer buffer, BuildTokensResult result) {
  final entries = <MapEntry<String, String>>[
    for (final t in result.colors) MapEntry(t.identifier, _colorDecl(t)),
    for (final t in result.scalars) MapEntry(t.identifier, _scalarDecl(t)),
    for (final c in result.plainConsts) MapEntry(c.identifier, _plainDecl(c)),
  ]..sort((a, b) => a.key.compareTo(b.key));
  for (final entry in entries) {
    buffer
      ..writeln(entry.value)
      ..writeln();
  }
}

String _colorDecl(ResolvedColorToken t) {
  final doc = _doc(t.doc, t.path);

  return "$doc\nconst ColorToken ${t.identifier} = ColorToken('${t.path}');";
}

String _scalarDecl(ResolvedScalarToken t) {
  final className = _mixClassNameFor(t.kind);
  final doc = _doc(t.doc, t.path);

  return "$doc\nconst $className ${t.identifier} = $className('${t.path}');";
}

String _mixClassNameFor(ScalarTokenKind kind) {
  final name = _mixClassName[kind];
  if (name == null) {
    // Unreachable in practice — every ScalarTokenKind value has an entry
    // above — but kept as a real check rather than a bang so a future enum
    // value that's forgotten here fails loudly instead of silently.
    throw StateError('No mix token class registered for $kind.');
  }

  return name;
}

String _plainDecl(PlainConstDecl c) {
  final doc = _doc(c.doc, c.identifier);

  return '$doc\nconst ${c.dartType} ${c.identifier} = ${c.valueSource};';
}

String _doc(String? description, String fallbackName) {
  final text = (description == null || description.isEmpty)
      ? 'Design token `$fallbackName`.'
      : description;

  return '/// ${text.replaceAll('\n', '\n/// ')}';
}

/// One shared, theme-independent `MixToken` value map: its generated
/// variable name, its `Map<K, V>` type arguments, and which
/// [ScalarTokenKind] feeds it.
///
// This file's name describes the whole emitter, not this single value-spec
// helper — same convention as core/architecture/mvc/test/mvc_test.dart.
// ignore: solid_lints/prefer_match_file_name
class _SharedMapSpec {
  const _SharedMapSpec(this.name, this.typeArgs, this.kind);

  final String name;
  final String typeArgs;
  final ScalarTokenKind kind;
}

const List<_SharedMapSpec> _sharedMapSpecs = [
  _SharedMapSpec('_spaces', 'SpaceToken, double', ScalarTokenKind.space),
  _SharedMapSpec('_radii', 'RadiusToken, Radius', ScalarTokenKind.radius),
  _SharedMapSpec('_doubles', 'DoubleToken, double', ScalarTokenKind.double_),
  _SharedMapSpec(
    '_textStyles',
    'TextStyleToken, TextStyle',
    ScalarTokenKind.textStyle,
  ),
  _SharedMapSpec(
    '_fontWeights',
    'FontWeightToken, FontWeight',
    ScalarTokenKind.fontWeight,
  ),
  _SharedMapSpec(
    '_durationTokens',
    'MixToken, Object',
    ScalarTokenKind.duration,
  ),
];

void _writeSharedValueMaps(StringBuffer buffer, BuildTokensResult result) {
  for (final spec in _sharedMapSpecs) {
    _writeMap(buffer, result.scalars, spec);
  }
}

void _writeMap(
  StringBuffer buffer,
  List<ResolvedScalarToken> scalars,
  _SharedMapSpec spec,
) {
  final entries = scalars.where((s) => s.kind == spec.kind).toList()
    ..sort((a, b) => a.identifier.compareTo(b.identifier));
  // `final`, not `const`: a MixToken overrides `==`/`hashCode` (it compares
  // by name), so it does not have the "primitive equality" the Dart
  // language requires of a `const` map's keys — only the individual token
  // declarations above are `const`, not these aggregate maps.
  buffer.writeln(
    'final Map<${spec.typeArgs}> ${spec.name} = <${spec.typeArgs}>{',
  );
  for (final entry in entries) {
    buffer.writeln('  ${entry.identifier}: ${entry.valueSource},');
  }
  buffer
    ..writeln('};')
    ..writeln();
}

void _writeThemedColorMaps(StringBuffer buffer, BuildTokensResult result) {
  final sortedColors = result.colors.toList()
    ..sort((a, b) => a.identifier.compareTo(b.identifier));
  for (final theme in result.themes) {
    _writeThemedColorMap(buffer, sortedColors, theme);
  }
}

void _writeThemedColorMap(
  StringBuffer buffer,
  List<ResolvedColorToken> sortedColors,
  String theme,
) {
  // `final`, not `const` — see the comment in `_writeMap`.
  buffer.writeln(
    'final Map<ColorToken, Color> _colors${_titleCase(theme)} = '
    '<ColorToken, Color>{',
  );
  for (final color in sortedColors) {
    final argb = color.argbByTheme[theme];
    if (argb == null) {
      // build_tokens.dart guarantees every color token resolves for every
      // discovered theme before this point is reached.
      throw StateError(
        'Token "${color.path}" has no value for theme "$theme".',
      );
    }
    final hex = argb.toRadixString(_hexRadix).padLeft(_argbHexDigits, '0');
    buffer.writeln('  ${color.identifier}: Color(0x$hex),');
  }
  buffer
    ..writeln('};')
    ..writeln();
}

String _titleCase(String value) => value[0].toUpperCase() + value.substring(1);

void _writeAppTokenValuesClass(StringBuffer buffer) {
  buffer.write('''
/// A resolved set of design-token values for one theme brightness, ready to
/// pass straight into `MixScope`'s typed parameters.
class AppTokenValues {
  /// Creates a resolved token value set.
  const AppTokenValues({
    required this.colors,
    required this.spaces,
    required this.radii,
    required this.doubles,
    required this.textStyles,
    required this.fontWeights,
    required this.tokens,
  });

  /// Color values, for `MixScope(colors: ...)`.
  final Map<ColorToken, Color> colors;

  /// Spacing values, for `MixScope(spaces: ...)`.
  final Map<SpaceToken, double> spaces;

  /// Corner-radius values, for `MixScope(radii: ...)`.
  final Map<RadiusToken, Radius> radii;

  /// General double values, for `MixScope(doubles: ...)`.
  final Map<DoubleToken, double> doubles;

  /// Text-style values, for `MixScope(textStyles: ...)`.
  final Map<TextStyleToken, TextStyle> textStyles;

  /// Font-weight values, for `MixScope(fontWeights: ...)`.
  final Map<FontWeightToken, FontWeight> fontWeights;

  /// Every other token value (e.g. durations), for `MixScope(tokens: ...)`.
  final Map<MixToken, Object> tokens;
}

''');
}

void _writeThemeInstances(StringBuffer buffer, BuildTokensResult result) {
  for (final theme in result.themes) {
    final title = _titleCase(theme);
    final varName = '${theme}Tokens';
    buffer.write('''
/// Resolved design-token values for the `$theme` theme.
///
/// `final`, not `const` — see the comment on the value maps it is built
/// from.
final AppTokenValues $varName = AppTokenValues(
  colors: _colors$title,
  spaces: _spaces,
  radii: _radii,
  doubles: _doubles,
  textStyles: _textStyles,
  fontWeights: _fontWeights,
  tokens: _durationTokens,
);

''');
  }
}
