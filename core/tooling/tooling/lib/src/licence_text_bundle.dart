/// One section of the `THIRD_PARTY_LICENSES` bundle
/// (`licence_bundle_command.dart`): a human-readable `heading` (package
/// name + version, `Flutter SDK <version>`, or a font's own licence
/// note) and the licence text itself, verbatim.
typedef LicenceBundleEntry = ({String heading, String licenceText});

/// Renders [entries] as the single `THIRD_PARTY_LICENSES` text file
/// `licence_bundle_command.dart` writes: a short preamble, then one
/// underlined section per entry, in the order given (the caller is
/// responsible for that order being deterministic — see
/// `licence_bundle_command.dart`'s own doc comment).
///
/// A pure function, kept separate from any file I/O, so
/// `licence_text_bundle_test.dart` can assert its exact shape without
/// touching disk.
String buildLicenceBundleText(List<LicenceBundleEntry> entries) {
  final buffer = StringBuffer()
    ..writeln('THIRD-PARTY LICENSES')
    ..writeln('=====================')
    ..writeln()
    ..writeln(
      'Generated by `melos run licence-bundle` '
      "(core/tooling/tooling's `licence_bundle` command). "
      'See docs/release-artifacts.md.',
    )
    ..writeln();

  for (final entry in entries) {
    final rule = '-' * entry.heading.length;
    buffer
      ..writeln(rule)
      ..writeln(entry.heading)
      ..writeln(rule)
      ..writeln()
      ..writeln(entry.licenceText.trim())
      ..writeln()
      ..writeln();
  }

  return buffer.toString();
}
